MODE_ORDER: tuple[Mode, ...] = (
    ASSISTANT,
    PROGRAMMER,
    TEACHER,
    BUSINESS,
    FRIEND,
    AUTOMATION,
)

MODES: dict[str, Mode] = {mode.id: mode for mode in MODE_ORDER}
DEFAULT_MODE = ASSISTANT.id


def get_mode(mode_id: str) -> Mode:
    try:
        return MODES[mode_id]
    except KeyError as exc:
        raise KeyError(mode_id) from exc


def mode_title(mode_id: str) -> str:
    mode = MODES.get(mode_id)
    if mode is None:
        return "Обычный помощник"
    return mode.title
